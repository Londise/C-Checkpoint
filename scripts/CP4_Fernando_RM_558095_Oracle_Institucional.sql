CREATE TABLE CATEGORIAS
(
    ID          NUMBER GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    NOME        VARCHAR2(100 CHAR) NOT NULL,
    DESCRICAO   VARCHAR2(500 CHAR),

    CONSTRAINT PK_CATEGORIAS PRIMARY KEY (ID),
    CONSTRAINT UQ_CATEGORIAS_NOME UNIQUE (NOME)
);

CREATE TABLE PRODUTOS
(
    ID                  NUMBER GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    NOME                VARCHAR2(150 CHAR) NOT NULL,
    DESCRICAO           VARCHAR2(500 CHAR),
    PRECO               NUMBER(12,2) NOT NULL,
    QUANTIDADEESTOQUE   NUMBER(10) NOT NULL,
    CATEGORIAID         NUMBER NOT NULL,

    CONSTRAINT PK_PRODUTOS PRIMARY KEY (ID),

    CONSTRAINT FK_PRODUTOS_CATEGORIAS
        FOREIGN KEY (CATEGORIAID)
        REFERENCES CATEGORIAS(ID),

    CONSTRAINT CK_PRODUTOS_PRECO
        CHECK (PRECO >= 0),

    CONSTRAINT CK_PRODUTOS_QTDE
        CHECK (QUANTIDADEESTOQUE >= 0)
);

CREATE INDEX IX_PRODUTOS_CATEGORIAID
    ON PRODUTOS(CATEGORIAID);

